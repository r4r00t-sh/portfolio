export function allSkills(): string[] {
  return skillCategories.flatMap((c) => c.items);
}

export function searchSkills(query: string): { category: SkillCategory; matches: string[] }[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return skillCategories
    .map((category) => ({
      category,
      matches: category.items.filter(
        (item) =>
          item.toLowerCase().includes(q) ||
          category.title.toLowerCase().includes(q) ||
          category.annotation.toLowerCase().includes(q),
      ),
    }))
    .filter((r) => r.matches.length > 0 || r.category.title.toLowerCase().includes(q));
}
